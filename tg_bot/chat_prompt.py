def build_static_parts(features_block: str = "") -> list[str]:
    """静态前缀：同一版本代码下每轮都一模一样，便于命中上下文缓存。"""
    parts = [STATIC_CORE]
    if features_block:
        parts.append(features_block)
    parts.append(REPORT_NOTE)
    return parts


def build_dynamic_parts(now_text: str, memory_context: str, toollog_lines: list[str] | None = None) -> list[str]:
    """动态尾部：时间、记忆、工具记录。"""
    parts = [
        f"【当前时间】今天是 {now_text}。训练数据可能滞后，以此为准；用户问几点了直接报这个时间。",
        "【对话记忆（仅用于保持连续性）】\n" + (memory_context or "")
        + "\n如果记忆中有相关记录，优先利用；没有时如实说明只能查看已保存的日志或摘要。",
    ]
    if toollog_lines:
        parts.append("\n".join(toollog_lines))
    return parts
